class Product {
  final String id;
  final String name;
  final String brand;
  final String image;
  final double price;
  final double rating;
  final String description;
  final String ram;
  final String storage;
  final String camera;
  final String battery;

  Product({
    required this.id,
    required this.name,
    required this.brand,
    required this.image,
    required this.price,
    required this.rating,
    required this.description,
    required this.ram,
    required this.storage,
    required this.camera,
    required this.battery,
  });
}
